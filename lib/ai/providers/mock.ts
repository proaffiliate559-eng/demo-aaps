import "server-only";

import type { OutfitProvider, ProviderResult, StylingContext } from "@/lib/ai/types";
import { BUDGETS } from "@/lib/config/options";

/**
 * DEVELOPMENT MOCK — returns fixed, clearly labelled placeholder looks so the
 * app can be developed and tested without an AI key. Outputs are stored with
 * is_mock = true and the UI labels them as "Development mock — not AI".
 * Never enabled implicitly; requires AI_PROVIDER=mock.
 */
export class MockOutfitProvider implements OutfitProvider {
  name = "mock";
  isMock = true;
  constructor(private ctx: () => StylingContext | null = () => null) {}

  async generateOutfits(): Promise<ProviderResult> {
    const ctx = this.ctx();
    const budget = BUDGETS.find((b) => b.value === ctx?.request.budget);
    const base = budget ? Math.round(((budget.min + (budget.max ?? budget.min * 1.5)) / 2) / 50) * 50 : 1500;
    const mood = ctx?.request.mood ?? "relaxed";
    const tier = (t: "safe" | "trendy" | "bold", i: number) => ({
      tier: t,
      name: `[MOCK] ${t[0].toUpperCase() + t.slice(1)} ${mood} look`,
      style: ctx?.request.style ?? "casual",
      description: "Development placeholder — not generated by AI.",
      items: {
        top: ["White cotton shirt", "Sage oversized tee", "Rust printed short kurta"][i],
        bottom: ["Beige chinos", "Wide-leg trousers", "Black straight jeans"][i],
        footwear: ["White sneakers", "Chunky trainers", "Kolhapuri sandals"][i],
        accessories: [["Minimal watch"], ["Canvas tote"], ["Oxidised silver bracelet"]][i],
        outerwear: null,
      },
      color_palette: [
        [{ name: "White", hex: "#F7F5F0" }, { name: "Beige", hex: "#D8C7AC" }],
        [{ name: "Sage", hex: "#B6C0A3" }, { name: "Cream", hex: "#EFE9DC" }],
        [{ name: "Rust", hex: "#B4552D" }, { name: "Black", hex: "#1D1A17" }],
      ][i],
      styling_explanation: "Mock output for testing the interface.",
      occasion_suitability: "Mock output for testing the interface.",
      estimated_budget_inr: base + i * 100,
      alternatives: ["Mock alternative"],
      styling_tips: ["Mock tip — connect an AI provider for real recommendations."],
    });
    return {
      raw: { outfits: [tier("safe", 0), tier("trendy", 1), tier("bold", 2)] },
      provider: this.name,
      model: "mock",
      isMock: true,
    };
  }
}
